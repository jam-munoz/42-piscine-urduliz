int	ft_addition(int x, int y)
{
	return (x + y);
}

int	ft_substraction(int x, int y)
{
	return (x - y);
}

int	ft_multiplication(int x, int y)
{
	return (x * y);
}

int	ft_division(int x, int y)
{
	return (x / y);
}

int	ft_modulus(int x, int y)
{
	return (x % y);
}

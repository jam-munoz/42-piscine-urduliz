int	ft_strcmp(char *s1, char *s2)
{
	int	len;
	int	i;

	len = 0;
	while(s1[len])
		len++;
	i = 0;
	while (i <= len)
	{
		if (s1[i] != s2[i])
			return (s1[i] - s2[i]);
		i++;
	}
	return (0);
}